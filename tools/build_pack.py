"""Build the Spoken pack from the recorded clips: SpokenCommunity_ivrit, as a folder and a zip.

    python tools/build_pack.py --version 0.1.0

1. Encodes each clip once to Ogg Vorbis q0 (the format Spoken's own packs ship) and copies it to
   every file name that needs it: build/store/{quests,followup}/<stem>.ogg.
2. Runs Spoken's own builder (vendor/spoken-wow/pipelines/quests/cli-main.py build) with
   --language heIL, which writes the TOC, Module.lua and the lookup tables the addon reads.
3. Zips build/dist/SpokenCommunity_ivrit into build/SpokenCommunity_ivrit-<version>.zip and
   prints its size and SHA-256 (what community/packs.json asks for).

Spoken plays the pack only once it knows heIL (see README.md); until then it would be read
as English, so do not hand it to other players before that.
"""
import argparse
import hashlib
import pathlib
import shutil
import subprocess
import sys
import zipfile

from common import HERE, load_json, pack_files, units

MODULE = "SpokenCommunity_ivrit"
SPOKEN = HERE / "vendor" / "spoken-wow" / "pipelines" / "quests"
PYTHON = HERE / ".venv" / "Scripts" / "python.exe"
# A face with Hebrew letters for the captions (the game's own fonts have none). It ships inside a
# pack other players download, so it has to be a font we may share: Noto Sans Hebrew merged with
# Noto Sans's Latin and punctuation (tools/make_font.py), SIL OFL 1.1, whose licence travels in
# the font's own metadata. Windows' Arial and Gisha may not be shared.
FONT = HERE / "fonts" / "SpokenHebrewSans-Regular.ttf"
# Hebrew.lua tries a second face when the client will not load the first; with one open font,
# both are the same file.
FONT_FALLBACK = FONT


def encode(mp3, ogg):
    ogg.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(mp3), "-ac", "1",
                    "-c:a", "libvorbis", "-q:a", "0", str(ogg)], check=True)


def display(text):
    """The Hebrew as players read it: the niqqud that steers the voice taken out (the game's
    font engine would draw the marks beside their letters, not on them), maqaf as a hyphen."""
    out = []
    for ch in text:
        if ch == "־":
            out.append("-")
        elif "֑" <= ch <= "ׇ":
            continue
        else:
            out.append(ch)
    return " ".join("".join(out).split())


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def add_captions(module_dir):
    """Hebrew captions: generated\\hebrew_text.lua (file stem -> Hebrew), addon/Hebrew.lua (shows
    them right-to-left in Spoken's subtitle and player window) and a font with Hebrew glyphs."""
    texts = {}
    for zone in units():
        he = load_json(HERE / "lines" / f"{zone}.he.json", {}).get("lines", {})
        for clip in load_json(HERE / "lines" / f"{zone}.en.json", []):
            if clip["id"] not in he or not (HERE / "audio" / f"{clip['id']}.mp3").exists():
                continue
            for rel in pack_files(clip):
                texts[rel.rsplit("/", 1)[1]] = display(he[clip["id"]])
    rows = "\n".join(f"    [{lua_string(stem)}] = {lua_string(text)}," for stem, text in sorted(texts.items()))
    (module_dir / "generated" / "hebrew_text.lua").write_text(
        f"-- Generated by tools/build_pack.py: each sound file's Hebrew caption.\n"
        f"{MODULE}.HebrewText = {{\n{rows}\n}}\n", encoding="utf-8")
    shutil.copyfile(HERE / "addon" / "Hebrew.lua", module_dir / "Hebrew.lua")
    (module_dir / "fonts").mkdir(exist_ok=True)
    shutil.copyfile(FONT, module_dir / "fonts" / "hebrew.ttf")
    shutil.copyfile(FONT_FALLBACK, module_dir / "fonts" / "hebrew2.ttf")
    toc = module_dir / f"{MODULE}.toc"
    text = toc.read_text(encoding="utf-8").rstrip("\n")
    toc.write_text(text + "\ngenerated\\hebrew_text.lua\nHebrew.lua\n", encoding="utf-8")
    print(f"captions: {len(texts)} lines, font {FONT.name}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    args = ap.parse_args()

    build = HERE / "build"
    store = build / "store"
    shutil.rmtree(store, ignore_errors=True)
    files = clips = missing = 0
    for zone in units():
        for clip in load_json(HERE / "lines" / f"{zone}.en.json", []):
            if not pack_files(clip):  # only a female-player variant: not shipped
                continue
            mp3 = HERE / "audio" / f"{clip['id']}.mp3"
            if not mp3.exists():
                missing += 1
                continue
            ogg = build / "ogg" / f"{clip['id']}.ogg"
            if not ogg.exists() or ogg.stat().st_mtime < mp3.stat().st_mtime:
                encode(mp3, ogg)
            clips += 1
            for rel in pack_files(clip):
                dest = store / f"{rel}.ogg"
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(ogg, dest)
                files += 1
    print(f"{clips} clips -> {files} files ({missing} clips not recorded yet)")

    # Spoken's builder wants a language badge icon; Hebrew has none upstream yet.
    icon = SPOKEN / "assets" / "icon" / "spoken-quests-heIL.tga"
    if not icon.exists():
        shutil.copyfile(SPOKEN / "assets" / "icon" / "spoken-quests.tga", icon)

    dist = build / "dist"
    shutil.rmtree(dist / MODULE, ignore_errors=True)
    subprocess.run([str(PYTHON), "cli-main.py", "build", "--store", str(store), "--dist", str(dist),
                    "--module", MODULE, "--pack", "all", "--language", "heIL", "--version", args.version,
                    "--module-title", "Spoken Hebrew (Ivrit)"], cwd=SPOKEN, check=True)

    add_captions(dist / MODULE)

    zip_path = build / f"{MODULE}-{args.version}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted((dist / MODULE).rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(dist).as_posix())
    digest = hashlib.sha256(zip_path.read_bytes()).hexdigest()
    print(f"\n{zip_path}\n  size {zip_path.stat().st_size} bytes\n  sha256 {digest}")


if __name__ == "__main__":
    sys.exit(main())
